export const LANGS = Object.freeze(["ja", "en"]);
let current = "ja";

export function setLang(lang) {
  current = MESSAGES[lang] ? lang : "ja";
}

export function getLang() {
  return current;
}

// 最初の言語: URL の ?lang= → 保存した選択 → ブラウザーの言語（日本語なら ja、それ以外は en）
export function chooseLang({ param, stored, browser } = {}) {
  if (LANGS.includes(param)) return param;
  if (LANGS.includes(stored)) return stored;
  return String(browser || "").toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function t(key, params = {}) {
  const dict = MESSAGES[current] || MESSAGES.ja;
  const s = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : MESSAGES.ja[key];
  if (typeof s !== "string") return key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : m));
}
